"""Emit the TypeScript tile table from the Python definition.

The classifier's output layer is indexed by position in `tileset.TILES`. If the
app's table ever drifts from the Python one - a class inserted, two swapped -
every prediction silently shifts and the bug looks like a bad model rather than
a bad constant. Generating one from the other removes the possibility.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from tileset import TILES, NUM_CLASSES, copies  # noqa: E402

HEADER = """// Generated by ml/src/export_tileset_ts.py - do not edit by hand.
//
// The order of this table is the classifier's output order. Regenerate it
// with `python3 ml/src/export_tileset_ts.py` if the tile set ever changes,
// and retrain: an edit here without a retrain silently relabels every
// prediction.

export type Suit = 'man' | 'pin' | 'sou' | 'wind' | 'dragon' | 'flower' | 'season';

export type TileCode =
"""


def main() -> None:
    out_path = Path(__file__).resolve().parents[2] / "mobile" / "src" / "tiles" / "tileset.ts"
    lines: list[str] = [HEADER]

    lines.append("\n".join(f"  | '{t.code}'" for t in TILES) + ";\n")

    lines.append("""
export interface TileDefinition {
  /** Frozen class index; matches the classifier's output layer. */
  readonly index: number;
  readonly code: TileCode;
  readonly suit: Suit;
  /** 1-9 for numbered suits, 1-4 for winds/flowers/seasons, 1-3 for dragons. */
  readonly rank: number;
  /** The character on the physical tile, where one exists. */
  readonly glyph: string;
  readonly label: string;
  /** Copies in a full 144-tile set: 4 for suits and honours, 1 for bonuses. */
  readonly copies: number;
}

export const TILES: readonly TileDefinition[] = [
""")

    for t in TILES:
        glyph = t.glyph.replace("'", "\\'")
        lines.append(
            f"  {{ index: {t.index}, code: '{t.code}', suit: '{t.suit.value}', "
            f"rank: {t.rank}, glyph: '{glyph}', label: '{t.label}', copies: {copies(t)} }},\n"
        )

    lines.append("""] as const;

export const NUM_CLASSES = %d;

export const TILE_BY_CODE: Readonly<Record<TileCode, TileDefinition>> = Object.fromEntries(
  TILES.map((tile) => [tile.code, tile]),
) as Record<TileCode, TileDefinition>;

export const TILE_BY_INDEX: readonly TileDefinition[] = TILES;

export const NUMBERED_SUITS = ['man', 'pin', 'sou'] as const;
export const HONOUR_SUITS = ['wind', 'dragon'] as const;
export const BONUS_SUITS = ['flower', 'season'] as const;

export const WIND_CODES = ['east', 'south', 'west', 'north'] as const;
export const DRAGON_CODES = ['red', 'green', 'white'] as const;

export type Wind = (typeof WIND_CODES)[number];

export function isNumbered(tile: TileDefinition): boolean {
  return tile.suit === 'man' || tile.suit === 'pin' || tile.suit === 'sou';
}

export function isHonour(tile: TileDefinition): boolean {
  return tile.suit === 'wind' || tile.suit === 'dragon';
}

/** Flowers and seasons sit outside the hand and never form melds. */
export function isBonus(tile: TileDefinition): boolean {
  return tile.suit === 'flower' || tile.suit === 'season';
}

export function isTerminal(tile: TileDefinition): boolean {
  return isNumbered(tile) && (tile.rank === 1 || tile.rank === 9);
}

export function isSimple(tile: TileDefinition): boolean {
  return isNumbered(tile) && tile.rank >= 2 && tile.rank <= 8;
}

/** Terminals and honours - the "yāojiǔ" set that many patterns turn on. */
export function isTerminalOrHonour(tile: TileDefinition): boolean {
  return isTerminal(tile) || isHonour(tile);
}

/** Class codes in classifier output order. */
export const CODES: readonly TileCode[] = TILES.map((tile) => tile.code);

export function tileAt(code: TileCode): TileDefinition {
  return TILE_BY_CODE[code];
}

/** The tile `steps` places along in the same numbered suit, or null. */
export function tileOffset(code: TileCode, steps: number): TileCode | null {
  const tile = TILE_BY_CODE[code];
  if (!isNumbered(tile)) return null;
  const rank = tile.rank + steps;
  if (rank < 1 || rank > 9) return null;
  return `${tile.suit}${rank}` as TileCode;
}
""" % NUM_CLASSES)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {NUM_CLASSES} tiles -> {out_path}")
    emit_asset_map()




def emit_asset_map() -> None:
    """Emit the static require() map for the bundled tile images.

    Metro resolves require() at build time, so the paths cannot be built from a
    variable - every one of the 42 has to be written out. Generating the file
    keeps it in step with the tile table instead of drifting from it.
    """
    out_path = Path(__file__).resolve().parents[2] / "mobile" / "src" / "tiles" / "assets.ts"
    lines = [
        "// Generated by ml/src/export_tileset_ts.py - do not edit by hand.\n",
        "//\n",
        "// Metro resolves require() statically, so each path must be a literal.\n",
        "\n",
        "import type { ImageSourcePropType } from 'react-native';\n",
        "import type { TileCode } from './tileset';\n",
        "\n",
        "export const TILE_IMAGES: Readonly<Record<TileCode, ImageSourcePropType>> = {\n",
    ]
    for t in TILES:
        lines.append(f"  {t.code}: require('@/assets/tiles/{t.code}.png'),\n")
    lines.append("};\n\nexport const TILE_BACK_IMAGE: ImageSourcePropType = require('@/assets/tiles/_back.png');\n")
    out_path.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote asset map -> {out_path}")


if __name__ == "__main__":
    main()
